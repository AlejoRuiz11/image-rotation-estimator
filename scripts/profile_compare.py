"""Profile the full `rotest compare` pipeline on a large synthetic pair.

Usage: uv run python scripts/profile_compare.py [--work-size N] [--threads N] [--grid] [--sign]
       [--keep DIR]

The pair is generated by code with a fixed seed and written as PNG to a temporary directory
outside the repo (or to --keep DIR); generation is not timed. Each stage of the real pipeline
(load_gray, resize, CLAHE, the register sub-stages and the bootstrap through the progress
callback, and write_report) is timed with wall time and CPU time, then printed as a Markdown
table. SIFT keypoint counts are captured by wrapping `rotest.register._detect`.

`--grid` also prints the angle error of the 9 cases of tests/test_accuracy.py and its sign test;
it reuses tests/synthetic.py and tests/test_accuracy.py by adding `tests/` to `sys.path`.
`--sign` repeats the large pair with the moving image generated for a truth angle +10 deg
larger and reports the measured difference.
"""

from __future__ import annotations

import argparse
import ctypes
import os
import platform
import sys
import tempfile
import time
from collections.abc import Callable
from pathlib import Path

import cv2
import numpy as np

import rotest.register as register_module
from rotest.geometry import to_matrix
from rotest.io import (
    DEFAULT_WORK_SIZE,
    Prepared,
    apply_clahe,
    compute_scale_factor,
    load_gray,
    resize_by_factor,
)
from rotest.register import Result, register, set_threads
from rotest.report import write_report
from rotest.uncertainty import SpatialCheck, angle_ci95, angle_uncertainty, spatial_check

SEED = 0
MOVING_SIZE = (6400, 8200)  # (width, height)
REFERENCE_SIZE = (10000, 11500)
TRUE_ANGLE_CW = 7.3
TRUE_SCALE = 1.05
SIGN_DELTA_DEG = 10.0
NOISE_SIGMA = 3

STAGE_ORDER = [
    "load",
    "resize",
    "clahe",
    "detect_moving",
    "detect_reference",
    "match",
    "ransac",
    "refine",
    "bootstrap",
    "spatial",
    "report",
]


# ----- synthetic pair -----------------------------------------------------------------------


def make_world(size: tuple[int, int], seed: int) -> np.ndarray:
    """Large blobby texture with many distinct keypoints at several scales."""
    w, h = size
    rng = np.random.default_rng(seed)
    img = np.full((h, w), 90, np.uint8)
    n = int(w * h / 1000)
    xs = rng.integers(0, w, n)
    ys = rng.integers(0, h, n)
    radii = rng.integers(6, 70, n)
    values = rng.integers(30, 255, n)
    for x, y, r, v in zip(xs, ys, radii, values, strict=True):
        cv2.circle(img, (int(x), int(y)), int(r), int(v), -1)
    # Second layer of small, fine details so SIFT finds keypoints at the working scale too.
    m = int(w * h / 1500)
    xs, ys = rng.integers(0, w, m), rng.integers(0, h, m)
    radii, values = rng.integers(2, 7, m), rng.integers(30, 255, m)
    for x, y, r, v in zip(xs, ys, radii, values, strict=True):
        cv2.circle(img, (int(x), int(y)), int(r), int(v), -1)
    return cv2.GaussianBlur(img, (0, 0), 1.5)


def add_noise(img: np.ndarray, seed: int) -> np.ndarray:
    """Add Gaussian noise in row chunks to avoid a float64 copy of a 100 MP image."""
    rng = np.random.default_rng(seed)
    for r0 in range(0, img.shape[0], 500):
        chunk = img[r0 : r0 + 500].astype(np.int16)
        chunk += np.rint(rng.normal(0.0, NOISE_SIGMA, chunk.shape)).astype(np.int16)
        img[r0 : r0 + 500] = np.clip(chunk, 0, 255).astype(np.uint8)
    return img


def make_moving(world: np.ndarray, angle_cw: float) -> np.ndarray:
    """Cut a moving image out of `world`: moving -> world is (angle_cw, TRUE_SCALE), centred."""
    mw, mh = MOVING_SIZE
    ww, wh = REFERENCE_SIZE
    rot = to_matrix(angle_cw, TRUE_SCALE, 0.0, 0.0)
    c_m = np.array([(mw - 1) / 2, (mh - 1) / 2])
    c_w = np.array([(ww - 1) / 2, (wh - 1) / 2])
    matrix = to_matrix(angle_cw, TRUE_SCALE, *(c_w - rot[:, :2] @ c_m))
    # WARP_INVERSE_MAP: dst(p) = src(M p), i.e. each moving pixel samples the world at M p.
    moving = cv2.warpAffine(
        world, matrix, (mw, mh), flags=cv2.INTER_LINEAR | cv2.WARP_INVERSE_MAP
    )
    return add_noise(moving, SEED + 1)


# ----- measurement --------------------------------------------------------------------------


class Timer:
    """Accumulates wall and CPU seconds per named stage."""

    def __init__(self) -> None:
        self.wall: dict[str, float] = {}
        self.cpu: dict[str, float] = {}
        self._open: dict[str, tuple[float, float]] = {}

    def start(self, stage: str) -> None:
        self._open[stage] = (time.perf_counter(), time.process_time())

    def stop(self, stage: str) -> None:
        w0, c0 = self._open.pop(stage)
        self.wall[stage] = self.wall.get(stage, 0.0) + time.perf_counter() - w0
        self.cpu[stage] = self.cpu.get(stage, 0.0) + time.process_time() - c0

    def timed(self, stage: str, fn: Callable[[], object]):
        self.start(stage)
        try:
            return fn()
        finally:
            self.stop(stage)

    def progress(self, stage: str, fraction: float) -> None:
        """Progress callback: only the 0.0 and 1.0 events delimit a stage."""
        if fraction == 0.0:
            self.start(stage)
        elif fraction == 1.0:
            self.stop(stage)


def prepare_timed(path: Path, timer: Timer, work_size: int) -> Prepared:
    """Same steps as `rotest.io.prepare` (no mask), timed per step."""
    gray = timer.timed("load", lambda: load_gray(path))
    h, w = gray.shape
    factor = compute_scale_factor((h, w), work_size)
    small = timer.timed("resize", lambda: resize_by_factor(gray, factor))
    image = timer.timed("clahe", lambda: apply_clahe(small))
    return Prepared(image=image, mask=None, scale_factor=factor, original_size=(w, h))


def run_pipeline(
    moving_path: Path, reference_path: Path, work_size: int
) -> tuple[Timer, float, float, Result, tuple[float, float], SpatialCheck, list[int]]:
    """Run the real pipeline once; return timer, total wall/cpu, result, CI and keypoint counts."""
    timer = Timer()
    keypoints: list[int] = []
    original_detect = register_module._detect

    def counting_detect(img, mask):
        kp, des = original_detect(img, mask)
        keypoints.append(len(kp))
        return kp, des

    register_module._detect = counting_detect
    w0, c0 = time.perf_counter(), time.process_time()
    try:
        moving = prepare_timed(moving_path, timer, work_size)
        reference = prepare_timed(reference_path, timer, work_size)
        result = register(moving, reference, timer.progress)
        ci = angle_ci95(result, progress=timer.progress)
        spatial = spatial_check(result, progress=timer.progress)
        with tempfile.TemporaryDirectory() as out:
            timer.timed("report", lambda: write_report(out, moving, reference, result, ci, spatial))
    finally:
        register_module._detect = original_detect
    return timer, time.perf_counter() - w0, time.process_time() - c0, result, ci, spatial, keypoints


def print_table(timer: Timer, total_wall: float, total_cpu: float) -> None:
    print("| stage | wall (s) | CPU (s) | CPU/wall | % of total |")
    print("|---|---:|---:|---:|---:|")
    for stage in STAGE_ORDER:
        wall, cpu = timer.wall.get(stage, 0.0), timer.cpu.get(stage, 0.0)
        ratio = cpu / wall if wall else 0.0
        print(f"| {stage} | {wall:.2f} | {cpu:.2f} | {ratio:.2f} | {100 * wall / total_wall:.1f} |")
    other_w = total_wall - sum(timer.wall.values())
    other_c = total_cpu - sum(timer.cpu.values())
    ratio = other_c / other_w if other_w > 0 else 0.0
    print(f"| other (between stages) | {other_w:.2f} | {other_c:.2f} | {ratio:.2f} | "
          f"{100 * other_w / total_wall:.1f} |")
    print(f"| **total** | {total_wall:.2f} | {total_cpu:.2f} | {total_cpu / total_wall:.2f} | 100.0 |")


def machine_info() -> str:
    ram = "unknown"
    if sys.platform == "win32":

        class MemoryStatus(ctypes.Structure):
            _fields_ = [
                ("length", ctypes.c_ulong),
                ("load", ctypes.c_ulong),
                ("total_phys", ctypes.c_ulonglong),
                ("avail_phys", ctypes.c_ulonglong),
                ("total_page", ctypes.c_ulonglong),
                ("avail_page", ctypes.c_ulonglong),
                ("total_virtual", ctypes.c_ulonglong),
                ("avail_virtual", ctypes.c_ulonglong),
                ("avail_ext", ctypes.c_ulonglong),
            ]

        status = MemoryStatus()
        status.length = ctypes.sizeof(MemoryStatus)
        ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(status))
        ram = f"{status.total_phys / 2**30:.1f} GiB"
    elif hasattr(os, "sysconf"):
        ram = f"{os.sysconf('SC_PAGE_SIZE') * os.sysconf('SC_PHYS_PAGES') / 2**30:.1f} GiB"
    return (
        f"cpu: {platform.processor()}, logical cores: {os.cpu_count()}, RAM: {ram}, "
        f"os: {platform.platform()}, python: {platform.python_version()}, "
        f"opencv: {cv2.__version__}, cv2 threads: {cv2.getNumThreads()}"
    )


# ----- accuracy grid (small synthetic pairs from the test-suite) ----------------------------


def run_grid() -> None:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tests"))
    from synthetic import make_pair, prepare, texture
    from test_accuracy import CASES

    print("\n### Accuracy grid (tests/test_accuracy.py cases)\n")
    print("| angle | scale | noise | crop | estimated angle | angle error (deg) |")
    print("|---:|---:|---:|---:|---:|---:|")
    for angle, scale, noise, crop in CASES:
        mov, ref, (a, _, _, _) = make_pair(angle, scale, noise, crop)
        r = register(mov, ref)
        print(
            f"| {angle} | {scale} | {noise} | {crop} | {r.angle_cw_deg:.4f} | "
            f"{r.angle_cw_deg - a:+.4f} |"
        )

    ref_img = texture()
    c = (ref_img.shape[0] - 1) / 2
    rot = to_matrix(25.0, 1.0, 0.0, 0.0)
    tx = c - (rot[0, 0] * c + rot[0, 1] * c)
    ty = c - (rot[1, 0] * c + rot[1, 1] * c)
    mov_img = cv2.warpAffine(ref_img, to_matrix(25.0, 1.0, tx, ty), ref_img.shape[::-1])
    r = register(prepare(mov_img), prepare(ref_img))
    print(f"\nSign test (expected -25): estimated {r.angle_cw_deg:.4f}, "
          f"error {r.angle_cw_deg + 25.0:+.4f} deg")


# ----- main ---------------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--work-size", type=int, default=DEFAULT_WORK_SIZE)
    parser.add_argument("--threads", type=int, help="cv2.setNumThreads(N); default: OpenCV's own, i.e. all cores")
    parser.add_argument("--grid", action="store_true", help="also print the accuracy grid")
    parser.add_argument("--sign", action="store_true", help="also run the +10 deg sign check")
    parser.add_argument("--keep", metavar="DIR", help="keep the generated PNGs in DIR")
    args = parser.parse_args()

    if args.threads is not None:
        set_threads(args.threads)
    print(f"machine: {machine_info()}")
    print(f"work-size: {args.work_size}")

    with tempfile.TemporaryDirectory() as tmp:
        work_dir = Path(args.keep) if args.keep else Path(tmp)
        work_dir.mkdir(parents=True, exist_ok=True)
        print(f"generating pair in {work_dir} (not timed)...", flush=True)
        world = make_world(REFERENCE_SIZE, SEED)
        reference = add_noise(world.copy(), SEED + 2)
        cv2.imwrite(str(work_dir / "reference.png"), reference)
        cv2.imwrite(str(work_dir / "moving.png"), make_moving(world, TRUE_ANGLE_CW))
        if args.sign:
            moving_rot = make_moving(world, TRUE_ANGLE_CW + SIGN_DELTA_DEG)
            cv2.imwrite(str(work_dir / "moving_rot.png"), moving_rot)
            del moving_rot
        del world, reference

        print(f"moving {MOVING_SIZE}, reference {REFERENCE_SIZE}, truth angle "
              f"{TRUE_ANGLE_CW} deg cw, scale {TRUE_SCALE}\n", flush=True)
        timer, wall, cpu, result, ci, spatial, kps = run_pipeline(
            work_dir / "moving.png", work_dir / "reference.png", args.work_size
        )
        print_table(timer, wall, cpu)
        print(
            f"\nkeypoints: moving {kps[0]}, reference {kps[1]}; matches (ratio test) "
            f"{result.matches}; inliers {result.inliers}"
        )
        print(
            f"angle: {result.angle_cw_deg:.4f} deg (truth {TRUE_ANGLE_CW}, error "
            f"{result.angle_cw_deg - TRUE_ANGLE_CW:+.4f}); CI95 [{ci[0]:.4f}, {ci[1]:.4f}]; "
            f"scale {result.scale:.4f} (truth {TRUE_SCALE})"
        )
        dev = spatial.angle_dev_deg
        print(
            f"angle_dev_deg: {'n/a' if dev is None else f'{dev:.4f}'}; "
            f"angle_uncertainty: +-{angle_uncertainty(ci, spatial):.4f} deg"
        )

        if args.sign:
            print("\n### Sign check (moving generated for truth angle +10 deg larger)\n")
            _, _, _, rot_result, _, _, _ = run_pipeline(
                work_dir / "moving_rot.png", work_dir / "reference.png", args.work_size
            )
            diff = rot_result.angle_cw_deg - result.angle_cw_deg
            print(
                f"angle with rotated moving: {rot_result.angle_cw_deg:.4f}; measured difference "
                f"{diff:+.4f} deg (expected +{SIGN_DELTA_DEG}, error "
                f"{diff - SIGN_DELTA_DEG:+.4f})"
            )

    if args.grid:
        run_grid()
    return 0


if __name__ == "__main__":
    sys.exit(main())
